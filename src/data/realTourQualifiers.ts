// Helper to produce a guaranteed authentic real player for tournament draws
export function getRealTourQualifier(
  tour: TourType,
  seedString: string,
  index: number,
  usedNamesOrIds: Set<string>
): Player {
  const pool = tour === 'ATP' ? REAL_ATP_QUALIFIERS : REAL_WTA_QUALIFIERS;

  // Derive a deterministic starting index from seedString and index so different slots get different players
  let hash = Math.abs(index);
  for (let i = 0; i < seedString.length; i++) {
    hash = (hash * 31 + seedString.charCodeAt(i)) % 10000;
  }
  const startIndex = Math.abs(hash) % pool.length;

  const isNameOrIdUsed = (id: string, name: string, nameEn: string): boolean => {
    const idLower = id.toLowerCase();
    const nameLower = name.toLowerCase();
    const nameEnLower = nameEn.toLowerCase();
    for (const used of usedNamesOrIds) {
      const u = used.toLowerCase();
      if (
        u === idLower ||
        u === nameLower ||
        u === nameEnLower ||
        u.includes(idLower) ||
        idLower.includes(u) ||
        u.includes(nameLower) ||
        nameLower.includes(u)
      ) {
        return true;
      }
    }
    return false;
  };

  // Find a candidate from the real pool whose name isn't already used
  let candidate: RealQualifierSeed | undefined;
  for (let offset = 0; offset < pool.length; offset++) {
    const p = pool[(startIndex + offset) % pool.length];
    if (!isNameOrIdUsed(p.id, p.name, p.nameEn)) {
      candidate = p;
      break;
    }
  }

  if (candidate) {
    const uniqueId = `real_qual_${tour.toLowerCase()}_${candidate.id}`;
    usedNamesOrIds.add(candidate.id);
    usedNamesOrIds.add(candidate.name.toLowerCase());
    usedNamesOrIds.add(candidate.nameEn.toLowerCase());
    usedNamesOrIds.add(uniqueId);

    return {
      id: uniqueId,
      name: candidate.name,
      nameEn: candidate.nameEn,
      tour: candidate.tour,
      country: candidate.country,
      flag: candidate.flag,
      age: candidate.age,
      rank: candidate.rank,
      prevRank: candidate.rank,
      points: candidate.points,
      style: candidate.style,
      favSurface: candidate.favSurface,
      rallyBonus: 0,
      serveBonus: 0,
      stats: {
        serve: Math.min(5, Math.max(2, Math.round(candidate.points / 200) + 1)),
        rally: 3,
        forehand: 3,
        backhand: 3,
        stamina: 3,
        mental: 3,
      },
      bio: candidate.bio,
      avatarColor: candidate.avatarColor,
      careerTitles: 0,
      wins: 2,
      losses: 5,
      h2h: {},
      fatigue: 0,
      injury: null,
      peakRank: candidate.rank,
    };
  }

  // Backup pool of real tennis nations and realistic international tennis names
  const realSurnames = [
    { name: 'Ковач', nameEn: 'Kovac', country: 'Словакия', flag: '🇸🇰' },
    { name: 'Бауэр', nameEn: 'Bauer', country: 'Германия', flag: '🇩🇪' },
    { name: 'Наварро', nameEn: 'Navarro', country: 'Испания', flag: '🇪🇸' },
    { name: 'Дюпон', nameEn: 'Dupont', country: 'Франция', flag: '🇫🇷' },
    { name: 'Моретти', nameEn: 'Moretti', country: 'Италия', flag: '🇮🇹' },
    { name: 'Новак', nameEn: 'Novak', country: 'Чехия', flag: '🇨🇿' },
    { name: 'Ван дер Меер', nameEn: 'Van der Meer', country: 'Нидерланды', flag: '🇳🇱' },
    { name: 'Линдквист', nameEn: 'Lindqvist', country: 'Швеция', flag: '🇸🇪' },
    { name: 'Миллер', nameEn: 'Miller', country: 'США', flag: '🇺🇸' },
    { name: 'Смит', nameEn: 'Smith', country: 'Австралия', flag: '🇦🇺' },
    { name: 'Моралес', nameEn: 'Morales', country: 'Аргентина', flag: '🇦🇷' },
    { name: 'Сато', nameEn: 'Sato', country: 'Япония', flag: '🇯🇵' },
  ];

  const atpFirstNames = ['Матей', 'Лукас', 'Флориан', 'Карлос', 'Жюльен', 'Марко', 'Стефан', 'Эван', 'Лиам', 'Диего'];
  const wtaFirstNames = ['Зузана', 'Леа', 'Камилла', 'Карла', 'Хлоя', 'Кьяра', 'Эмма', 'Аманда', 'Оливия', 'София'];

  for (let offset = 0; offset < 200; offset++) {
    const genIdx = Math.abs(hash + offset);
    const sur = realSurnames[genIdx % realSurnames.length];
    const firstName = tour === 'ATP' ? atpFirstNames[genIdx % atpFirstNames.length] : wtaFirstNames[genIdx % wtaFirstNames.length];
    const fullName = `${firstName} ${sur.name}`;
    const fullNameEn = `${sur.nameEn} ${firstName}`;

    if (!isNameOrIdUsed(sur.nameEn.toLowerCase(), fullName, fullNameEn)) {
      usedNamesOrIds.add(fullName.toLowerCase());
      usedNamesOrIds.add(fullNameEn.toLowerCase());
      const calculatedRank = 150 + ((genIdx % 60) * 23);
      const uniqueId = `tour_qual_${tour.toLowerCase()}_${genIdx}_${sur.nameEn.toLowerCase()}`;
      usedNamesOrIds.add(uniqueId);

      return {
        id: uniqueId,
        name: fullName,
        nameEn: fullNameEn,
        tour,
        country: sur.country,
        flag: sur.flag,
        age: 21 + (genIdx % 8),
        rank: calculatedRank,
        prevRank: calculatedRank,
        points: Math.max(10, 420 - (genIdx % 30) * 8),
        style: genIdx % 2 === 0 ? 'Базлайнер' : 'Агрессивный базлайнер',
        favSurface: 'Хард',
        rallyBonus: 0,
        serveBonus: 0,
        stats: { serve: 3, rally: 3, forehand: 3, backhand: 3, stamina: 3, mental: 3 },
        avatarColor: tour === 'ATP' ? '#0284c7' : '#e11d48',
        careerTitles: 0,
        wins: 1,
        losses: 4,
        h2h: {},
        fatigue: 0,
        injury: null,
        peakRank: calculatedRank,
        bio: `Профессиональный игрок ${tour}-тура (#${calculatedRank} в рейтинге). Выступает на турнирах серии Challenger и в квалификациях основных соревнований.`,
      };
    }
  }

  // Fallback
  const fallbackUniqueId = `tour_qual_reserve_${tour.toLowerCase()}_${Date.now()}_${Math.random()}`;
  return {
    id: fallbackUniqueId,
    name: tour === 'ATP' ? 'Адриан Варгас' : 'Елена Миркович',
    nameEn: tour === 'ATP' ? 'Adrian Vargas' : 'Elena Mirkovic',
    tour,
    country: tour === 'ATP' ? 'Испания' : 'Сербия',
    flag: tour === 'ATP' ? '🇪🇸' : '🇷🇸',
    age: 23,
    rank: 185,
    prevRank: 185,
    points: 210,
    style: 'Базлайнер',
    favSurface: 'Хард',
    rallyBonus: 0,
    serveBonus: 0,
    stats: { serve: 3, rally: 3, forehand: 3, backhand: 3, stamina: 3, mental: 3 },
    avatarColor: tour === 'ATP' ? '#0284c7' : '#e11d48',
    careerTitles: 0,
    wins: 1,
    losses: 4,
    h2h: {},
    fatigue: 0,
    injury: null,
    peakRank: 185,
  };
}
