export function generateTourQualifiers(tour: 'ATP' | 'WTA', startIndex: number, count: number): Player[] {
  const roster = tour === 'ATP' ? REAL_ATP_QUALIFIERS_ROSTER : REAL_WTA_QUALIFIERS_ROSTER;
  const players: Player[] = [];

  for (let i = 0; i < count; i++) {
    const rank = startIndex + i;
    const bio = roster[i % roster.length];
    const baseStat = Math.max(68, Math.min(88, 88 - Math.floor((rank - 16) * 0.25)));

    players.push({
      id: `${tour.toLowerCase()}-${rank}`,
      name: bio.name,
      nameRu: bio.nameRu,
      country: bio.country,
      flag: bio.flag,
      age: bio.age,
      tour,
      rank,
      previousRank: rank,
      points: Math.max(100, Math.floor(2200 * Math.exp(-rank / 35))),
      previousPoints: Math.max(100, Math.floor(2200 * Math.exp(-rank / 35))),
      titles: rank < 40 ? ((i % 5 === 0) ? 1 : 0) : 0,
      careerTitles: rank < 30 ? (1 + (i % 3)) : (rank < 60 ? (i % 2) : 0),
      grandSlams: 0,
      matchesWon: Math.max(5, 30 - Math.floor(rank / 4)),
      matchesLost: Math.max(5, 15 + Math.floor(rank / 6)),
      prizeMoney: Math.max(50000, Math.floor(1800000 * Math.exp(-rank / 30))),
      form: 0.95 + ((i % 10) * 0.015),
      energy: 100,
      handedness: bio.handedness,
      backhandType: bio.backhandType,
      stats: {
        serve: Math.max(65, Math.min(95, baseStat + ((i * 5) % 9) - 4)),
        forehand: Math.max(65, Math.min(95, baseStat + ((i * 3) % 9) - 3)),
        backhand: Math.max(65, Math.min(95, baseStat + ((i * 7) % 9) - 4)),
        speed: Math.max(65, Math.min(95, baseStat + ((i * 2) % 9) - 2)),
        stamina: Math.max(65, Math.min(95, baseStat + ((i * 4) % 9) - 3)),
        mental: Math.max(65, Math.min(95, baseStat + ((i * 6) % 9) - 4)),
        clutch: Math.max(65, Math.min(95, baseStat + ((i * 8) % 9) - 4)),
        hardAffinity: 0.95 + ((i % 5) * 0.04),
        clayAffinity: 0.95 + (((i + 2) % 5) * 0.04),
        grassAffinity: 0.95 + (((i + 4) % 5) * 0.04),
      },
    });
  }

  return players;
}
