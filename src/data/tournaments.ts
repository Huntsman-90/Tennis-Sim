// Helper to determine points for a given round and tournament category
export function getRoundPoints(category: TournamentCategory, round: string, isWinner = false): number {
  if (isWinner) {
    if (category === 'Grand Slam') return 2000;
    if (category === 'ATP Masters 1000' || category === 'WTA 1000') return 1000;
    if (category === 'ATP 500' || category === 'WTA 500') return 500;
    if (category === 'ATP 250' || category === 'WTA 250') return 250;
    if (category === 'ATP Finals' || category === 'WTA Finals') return 1500;
    return 250;
  }

  if (category === 'Grand Slam') {
    if (round === 'F') return 1300;
    if (round === 'SF') return 800;
    if (round === 'QF') return 400;
    if (round === 'R16') return 200;
    if (round === 'R32') return 100;
    return 10;
  }

  if (category === 'ATP Masters 1000' || category === 'WTA 1000') {
    if (round === 'F') return 650;
    if (round === 'SF') return 400;
    if (round === 'QF') return 200;
    if (round === 'R16') return 100;
    if (round === 'R32') return 50;
    return 10;
  }

  if (category === 'ATP 500' || category === 'WTA 500') {
    if (round === 'F') return 330;
    if (round === 'SF') return 200;
    if (round === 'QF') return 100;
    if (round === 'R16') return 50;
    if (round === 'R32') return 25;
    return 0;
  }

  if (category === 'ATP 250' || category === 'WTA 250') {
    if (round === 'F') return 165;
    if (round === 'SF') return 100;
    if (round === 'QF') return 50;
    if (round === 'R16') return 25;
    if (round === 'R32') return 10;
    return 0;
  }

  if (category === 'ATP Finals' || category === 'WTA Finals') {
    if (round === 'F') return 1000;
    if (round === 'SF') return 600;
    return 400;
  }

  return 0;
}

// Backward-compatible alias
export const getWtaRoundPoints = getRoundPoints;
